/**
 * Homework, as the product owner's specification of 2026-09-13 has it
 * (docs/gurukul-spec-rules.md, "Homework — RULED 2026-09-13"):
 *
 *   * the question is EITHER typed text OR one uploaded file;
 *   * the deadline is one instant, `closes_at`; `due_date` is generated from it;
 *   * a student hands in ONE image or PDF, through `rpc_homework_submit`;
 *   * a teacher accepts or rejects, through `rpc_homework_decide`;
 *   * a student's standing — handed in or not, deadline passed or not — is
 *     decided in ONE place, the `homework_student_status` view.
 *
 * Nothing here restates a rule the database owns. Where the database refuses a
 * write, `homeworkError` and `refusalError` carry its refusal to the person in words.
 */

export type HomeworkStatus = "draft" | "scheduled" | "published" | "archived";
export type HomeworkPriority = "low" | "normal" | "high" | "urgent";
export type SubmissionStatus = "not_submitted" | "submitted" | "accepted" | "rejected";
export type HomeworkDecision = "accepted" | "rejected";

export interface HomeworkRecord {
  id: string;
  schoolId: string;
  classId: string;
  subject: string;
  title: string;
  /** The typed question; empty when the question is `questionFile`. */
  questionText: string;
  questionFile: AcademicFile | null;
  /** §10.22 — picked from the curriculum, never typed. */
  chapterId: string | null;
  topicId: string | null;
  /** §10.22's free-text label, where no chapter fits (the `topic` column). */
  chapterLabel: string | null;
  /** THE deadline. */
  closesAt: string;
  /** The deadline's school-local date, generated by the database. */
  dueDate: string;
  priority: HomeworkPriority;
  workKind: WorkKind;
  status: HomeworkStatus;
  scheduledPublishAt: string | null;
  publishedAt: string | null;
  archivedAt: string | null;
  resolvedAt: string | null;
  /**
   * Whether not giving it when it closes costs the student the missed-homework
   * XP. False only for homework released before that rule existed.
   */
  missedCostsXp: boolean;
  createdBy: string | null;
  createdAt: string;
  updatedAt: string;
}

