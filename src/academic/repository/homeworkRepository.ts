/** How many undeleted homework the school has in each status — exact counts, not a page. */
export async function countHomeworkByStatus(ctx: RepoContext): Promise<Record<HomeworkStatus, number>> {
  const statuses: HomeworkStatus[] = ["draft", "scheduled", "published", "archived"];
  const counts = await Promise.all(
    statuses.map(async (status) => {
      const { count, error } = await getClient(ctx)
        .from("homework")
        .select("id", { count: "exact", head: true })
        .eq("school_id", schoolIdOf(ctx))
        .eq("status", status)
        .is("deleted_at", null);
      throwIfError(error, "Failed to count homework");
      return [status, count ?? 0] as const;
    }),
  );
  return Object.fromEntries(counts) as Record<HomeworkStatus, number>;
}

export async function listHomeworkByIds(ctx: RepoContext, ids: string[]): Promise<HomeworkRecord[]> {
  if (ids.length === 0) return [];
  const { data, error } = await getClient(ctx)
    .from("homework")
    .select(HW_SELECT)
    .eq("school_id", schoolIdOf(ctx))
    .in("id", ids);
  throwIfError(error, "Failed to load homework");
  return (data ?? []).map((r) => mapHomework(r as HomeworkRow));
}

export async function createHomework(ctx: RepoContext, input: HomeworkInput): Promise<HomeworkRecord> {
  const { data, error } = await getClient(ctx)
    .from("homework")
    .insert({ ...rowFor(input), school_id: schoolIdOf(ctx) })
    .select(HW_SELECT)
    .single();
  homeworkError(error, "Failed to set homework");
  return mapHomework(data as HomeworkRow);
}

export async function updateHomework(
  ctx: RepoContext,
  homeworkId: string,
  patch: Partial<Pick<HomeworkRow, "status" | "scheduled_publish_at">> | HomeworkInput,
): Promise<HomeworkRecord> {
  const values = "classId" in patch ? (({ class_id: _class, ...rest }) => rest)(rowFor(patch)) : patch;
  const { data, error } = await getClient(ctx)
    .from("homework")
    .update(values)
    .eq("id", homeworkId)
    .eq("school_id", schoolIdOf(ctx))
    .select(HW_SELECT)
    .single();
  homeworkError(error, "Failed to update homework");
  return mapHomework(data as HomeworkRow);
}

/** Soft delete, through `rpc_homework_delete`: to the trash, out of every count. */
export async function deleteHomework(ctx: RepoContext, homeworkId: string): Promise<void> {
  const { error } = await getClient(ctx).rpc("rpc_homework_delete", { _homework_id: homeworkId });
  refusalError(error, "Failed to delete homework");
}

