-- VERIFICATION
--
-- Runs as `postgres`, which bypasses RLS, so it proves NOTHING about who any
-- fence admits (rule 6). It checks that the conversion is COMPLETE and that
-- nothing structural was lost in 71 rewrites. Who is admitted and who is
-- refused, across roles and across schools, is asserted as the caller in
-- probe25 (rule 7), on top of the 215 caller assertions that already cover
-- tenancy on many of these same tables and would fail if a fence had moved.
-- ═══════════════════════════════════════════════════════════════════════════
DO $verify$
DECLARE
  _left        int;
  _fences      int;
  _permissive  int;
  _no_using    int;
BEGIN
  -- 1. No tenant fence may still call same_school.
  SELECT count(*) INTO _left
    FROM pg_policy p JOIN pg_class c ON c.oid = p.polrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND p.polname LIKE '%tenant_fence%'
     AND (pg_get_expr(p.polqual, p.polrelid) LIKE '%same_school%'
       OR pg_get_expr(p.polwithcheck, p.polrelid) LIKE '%same_school%');
  IF _left <> 0 THEN
    RAISE EXCEPTION 'ABORT: % tenant fence(s) still call same_school', _left;
  END IF;

  -- 2. ...and the fences must still BE there. A conversion that dropped a
  --    policy instead of replacing it would satisfy check 1 perfectly.
  SELECT count(*) INTO _fences
    FROM pg_policy p JOIN pg_class c ON c.oid = p.polrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND p.polname LIKE '%tenant_fence%'
     AND pg_get_expr(p.polqual, p.polrelid) LIKE '%my_accessible_school_ids%';
  IF _fences < 71 THEN
    RAISE EXCEPTION 'ABORT: expected at least 71 converted fences, found %', _fences;
  END IF;

  -- 3. Every tenant fence must still be RESTRICTIVE. A fence recreated as
  --    PERMISSIVE stops being a fence and becomes another way IN -- the single
  --    most dangerous way this migration could go wrong.
  SELECT count(*) INTO _permissive
    FROM pg_policy p JOIN pg_class c ON c.oid = p.polrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND p.polname LIKE '%tenant_fence%' AND p.polpermissive;
  IF _permissive <> 0 THEN
    RAISE EXCEPTION 'ABORT: % tenant fence(s) are PERMISSIVE, not RESTRICTIVE', _permissive;
  END IF;

  -- 4. A fence with neither USING nor WITH CHECK constrains nothing.
  SELECT count(*) INTO _no_using
    FROM pg_policy p JOIN pg_class c ON c.oid = p.polrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND p.polname LIKE '%tenant_fence%'
     AND pg_get_expr(p.polqual, p.polrelid) IS NULL
     AND pg_get_expr(p.polwithcheck, p.polrelid) IS NULL;
  IF _no_using <> 0 THEN
    RAISE EXCEPTION 'ABORT: % tenant fence(s) have no predicate at all', _no_using;
  END IF;

  RAISE NOTICE 'tenant fences converted: % now use the set form; behaviour is in probe25.', _fences;
END $verify$;
