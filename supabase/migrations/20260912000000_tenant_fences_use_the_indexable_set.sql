-- 71 tenant fences stop being a per-row function call
--
-- ── THE DEFECT, MEASURED ─────────────────────────────────────────────────
--
-- `same_school(school_id)` takes the ROW's column as an argument, so it is a
-- function OF the row: it cannot be folded to a constant, cannot be answered
-- from an index, and is called once per row. Each call runs
-- `get_my_school_id()`, which runs `active_membership_school_id()` ->
-- `active_membership_id()` -> `current_auth_session_id()`. And because
-- `same_school` is SECURITY DEFINER, PostgreSQL will never inline it, so no
-- rewrite of its body can remove that per-row cost. The call site is what has
-- to change.
--
-- For a caller who matches NOTHING there is no early exit, so the whole table
-- is walked. Measured over real HTTP as the super admin, who matches nothing:
--
--   GET /rest/v1/academic_audit?select=id&order=created_at.desc&limit=6
--     -> 500 {"code":"57014","message":"canceling statement due to statement
--             timeout"}   after 8.5s, on 9,166 rows
--
--   GET /rest/v1/student_enrolments?select=id&limit=6
--     -> 200 in 949ms, on 223 rows
--
-- After the conversion, the same two requests:
--
--   academic_audit      500 timeout after 8,513ms  ->  200 in 729ms
--   student_enrolments  200 in 949ms               ->  200 in 396ms
--
-- WHAT THIS DID NOT DO, measured and stated so the header is not read as a
-- claim it cannot support: the app's ordinary paths did not get faster. The
-- Tier 1 write suite took 4.1 minutes with these fences converted and 4.0 with
-- them rolled back — the same, within noise. This fixes the PATHOLOGICAL case,
-- a caller who matches nothing on a table large enough for the scan to exceed
-- statement_timeout. That case was a 500 for real users and is now a 200; the
-- common case was already fast and is unchanged.
--
-- THIS IS NOT A SUPER-ADMIN PROBLEM. Any caller whose `get_my_school_id()` is
-- NULL walks the table, and 42 of 62 accounts hold no role. An admin escapes it
-- only by accident: they match on the first row and `LIMIT` stops the scan.
--
-- ── THE FIX IS THE PATTERN 31 FENCES ALREADY USE ─────────────────────────
--
--   school_id IN (SELECT public.my_accessible_school_ids())
--
-- A set membership. The set is computed ONCE per statement, the planner can use
-- the index on `school_id`, and a caller whose set is empty is answered without
-- reading a row. `exams`, `students` and `learning_resources` were already
-- written this way; this brings the remaining 71 into line.
--
-- ── WHY IT ADMITS EXACTLY THE SAME ROWS ──────────────────────────────────
--
--   same_school(x) = x IS NOT NULL
--                    AND ( x = get_my_school_id()
--                          OR (super_admin_has_any_access()
--                              AND super_admin_has_access(x)) )
--
--   my_accessible_school_ids() = { get_my_school_id() }  when non-null
--                              ∪ { schools with a live super-admin grant }
--
-- The same set, both branches. NULL differs only in form: `same_school(NULL)`
-- is false, `NULL IN (...)` is NULL, and both exclude a row in USING and fail
-- it in WITH CHECK. Every fence keeps its own `school_id IS NULL OR ...` branch
-- untouched, so that difference is not even reachable.
--
-- ── HOW THIS FILE WAS PRODUCED, AND WHY THAT MATTERS ─────────────────────
--
-- Generated by `scripts/gen-tenant-fence-migration.mjs`, which reads each
-- policy's LIVE definition and rewrites exactly one sub-expression, preserving
-- name, table, command, roles, RESTRICTIVE-ness and every other term verbatim.
-- 71 policies, 141 `same_school` calls, 0 left. Hand-transcribing 71 tenancy
-- fences is how one loses a term and a tenant leaks; the generator cannot make
-- that mistake, and `--rollback` emits the current definitions for the rollback
-- file from the same source.
--
-- ── WHAT IS DELIBERATELY NOT TOUCHED ─────────────────────────────────────
--
-- The 104 PERMISSIVE policies that also call `same_school`. They are evaluated
-- only for rows the RESTRICTIVE fence already admitted, so they are not what
-- turns a query into a full scan. Converting them would widen this change
-- without evidence that it helps, and the generator refuses to touch a
-- permissive policy rather than trusting the name filter alone.
--
-- §10.19 Multi-tenancy (docs/locked-decisions.md) -- one database, every school
-- fenced by RLS. This changes how the fence is EVALUATED, never who it admits;
-- probe25 asserts that as the caller, across roles and across schools.
-- ═══════════════════════════════════════════════════════════════════════════

