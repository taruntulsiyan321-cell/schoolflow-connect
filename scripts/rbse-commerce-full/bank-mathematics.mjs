/** Build 10 MCQs for a chapter from concept pairs [concept, ...question tuples] */
function expand(ch, blocks) {
  /** @type {import('./util.mjs').Q[]} */
  const out = [];
  for (const b of blocks) {
    const concept = b[0];
    for (let i = 1; i < b.length; i++) {
      const [q, o, c, e, diff] = b[i];
      out.push(Q(ch, concept, q, o, c, e, diff || "medium"));
    }
  }
  return out;
}

